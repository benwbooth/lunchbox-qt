#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct ParentRelationship {
    pub parent_platform_category_name: Option<String>,
    pub parent_platform_name: Option<String>,
    pub parent_playlist_id: Option<String>,
    pub platform_category_name: Option<String>,
    pub platform_name: Option<String>,
    pub playlist_id: Option<String>,
}

impl ParentRelationship {
    pub fn validate(&self) -> Result<(), CatalogValidationError> {
        let children = [
            self.platform_category_name.as_deref(),
            self.platform_name.as_deref(),
            self.playlist_id.as_deref(),
        ]
        .into_iter()
        .flatten()
        .filter(|value| !value.trim().is_empty())
        .count();
        if children != 1 {
            return Err(CatalogValidationError::InvalidParentChildCount { actual: children });
        }

        let parents = [
            self.parent_platform_category_name.as_deref(),
            self.parent_platform_name.as_deref(),
            self.parent_playlist_id.as_deref(),
        ]
        .into_iter()
        .flatten()
        .filter(|value| !value.trim().is_empty())
        .count();
        if parents > 1 {
            return Err(CatalogValidationError::InvalidParentTargetCount { actual: parents });
        }
        Ok(())
    }
}

