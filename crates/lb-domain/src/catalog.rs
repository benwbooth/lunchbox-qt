#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct FrontendSettings {
    pub source_path: PathBuf,
    pub record_name: String,
    pub entries: Vec<SettingEntry>,
    pub image_type_settings: Vec<ImageTypeSetting>,
}

impl FrontendSettings {
    pub fn get(&self, key: &str) -> Option<&str> {
        self.entries
            .iter()
            .find(|entry| entry.key == key)
            .map(|entry| entry.value.as_str())
    }

    pub fn get_bool(&self, key: &str) -> Option<bool> {
        match self.get(key)? {
            value if value.eq_ignore_ascii_case("true") => Some(true),
            value if value.eq_ignore_ascii_case("false") => Some(false),
            _ => None,
        }
    }

    pub fn get_i64(&self, key: &str) -> Option<i64> {
        self.get(key)?.parse().ok()
    }
}

fn require_field(
    record: &'static str,
    field: &'static str,
    value: &str,
) -> Result<(), CatalogValidationError> {
    if value.trim().is_empty() {
        Err(CatalogValidationError::MissingField { record, field })
    } else {
        Ok(())
    }
}

#[derive(Clone, Debug, Error, Eq, PartialEq)]
pub enum CatalogValidationError {
    #[error("{record} is missing its name")]
    MissingName { record: &'static str },
    #[error("{record} is missing required {field}")]
    MissingField {
        record: &'static str,
        field: &'static str,
    },
    #[error("{record} name occurs more than once: {name}")]
    DuplicateName { record: &'static str, name: String },
    #[error("Parent must identify exactly one child, found {actual}")]
    InvalidParentChildCount { actual: usize },
    #[error("Parent identifies more than one parent target, found {actual}")]
    InvalidParentTargetCount { actual: usize },
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parent_relationship_requires_one_child_and_at_most_one_parent() {
        let valid = ParentRelationship {
            parent_platform_category_name: Some("Consoles".into()),
            platform_name: Some("Fixture Console".into()),
            ..ParentRelationship::default()
        };
        assert_eq!(valid.validate(), Ok(()));

        let missing_child = ParentRelationship::default();
        assert_eq!(
            missing_child.validate(),
            Err(CatalogValidationError::InvalidParentChildCount { actual: 0 })
        );

        let ambiguous_parent = ParentRelationship {
            parent_platform_category_name: Some("Consoles".into()),
            parent_platform_name: Some("Arcade".into()),
            platform_name: Some("Fixture Console".into()),
            ..ParentRelationship::default()
        };
        assert_eq!(
            ambiguous_parent.validate(),
            Err(CatalogValidationError::InvalidParentTargetCount { actual: 2 })
        );
    }

    #[test]
    fn platform_catalog_rejects_case_insensitive_duplicate_names() {
        let mut catalog = PlatformCatalog::default();
        catalog.platforms.push(PlatformDefinition {
            metadata: NavigationMetadata {
                name: "Arcade".into(),
                ..NavigationMetadata::default()
            },
            ..PlatformDefinition::default()
        });
        catalog.platforms.push(PlatformDefinition {
            metadata: NavigationMetadata {
                name: "arcade".into(),
                ..NavigationMetadata::default()
            },
            ..PlatformDefinition::default()
        });
        assert_eq!(
            catalog.validate(),
            Err(CatalogValidationError::DuplicateName {
                record: "Platform",
                name: "arcade".into(),
            })
        );
    }

    #[test]
    fn platform_catalog_rejects_case_insensitive_duplicate_category_names() {
        let mut catalog = PlatformCatalog::default();
        catalog.categories.push(PlatformCategory {
            metadata: NavigationMetadata {
                name: "Collections".into(),
                ..NavigationMetadata::default()
            },
            ..PlatformCategory::default()
        });
        catalog.categories.push(PlatformCategory {
            metadata: NavigationMetadata {
                name: "collections".into(),
                ..NavigationMetadata::default()
            },
            ..PlatformCategory::default()
        });
        assert_eq!(
            catalog.validate(),
            Err(CatalogValidationError::DuplicateName {
                record: "PlatformCategory",
                name: "collections".into(),
            })
        );
    }

    #[test]
    fn parent_relationship_accepts_a_playlist_parent() {
        let relationship = ParentRelationship {
            parent_playlist_id: Some("favorites".into()),
            platform_category_name: Some("Handhelds".into()),
            ..ParentRelationship::default()
        };
        assert_eq!(relationship.validate(), Ok(()));
    }

    #[test]
    fn settings_accessors_do_not_guess_invalid_types() {
        let settings = FrontendSettings {
            entries: vec![
                SettingEntry {
                    key: "Enabled".into(),
                    value: "True".into(),
                },
                SettingEntry {
                    key: "Count".into(),
                    value: "12".into(),
                },
                SettingEntry {
                    key: "Theme".into(),
                    value: "Default".into(),
                },
            ],
            ..FrontendSettings::default()
        };
        assert_eq!(settings.get_bool("Enabled"), Some(true));
        assert_eq!(settings.get_i64("Count"), Some(12));
        assert_eq!(settings.get_bool("Theme"), None);
    }
}
