#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct PlatformCatalog {
    pub source_path: PathBuf,
    pub platforms: Vec<PlatformDefinition>,
    pub categories: Vec<PlatformCategory>,
    pub folders: Vec<PlatformFolder>,
}

impl PlatformCatalog {
    pub fn validate(&self) -> Result<(), CatalogValidationError> {
        let mut platform_names = BTreeSet::new();
        for platform in &self.platforms {
            platform.validate()?;
            let name = platform.metadata.name.to_lowercase();
            if !platform_names.insert(name) {
                return Err(CatalogValidationError::DuplicateName {
                    record: "Platform",
                    name: platform.metadata.name.clone(),
                });
            }
        }
        let mut category_names = BTreeSet::new();
        for category in &self.categories {
            category.validate()?;
            let name = category.metadata.name.to_lowercase();
            if !category_names.insert(name) {
                return Err(CatalogValidationError::DuplicateName {
                    record: "PlatformCategory",
                    name: category.metadata.name.clone(),
                });
            }
        }
        for folder in &self.folders {
            folder.validate()?;
        }
        Ok(())
    }
}

