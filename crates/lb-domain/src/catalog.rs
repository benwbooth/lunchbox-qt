impl NavigationMetadata {
    pub fn validate(&self, record: &'static str) -> Result<(), CatalogValidationError> {
        if self.name.trim().is_empty() {
            return Err(CatalogValidationError::MissingName { record });
        }
        Ok(())
    }
}

